create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  role text not null default 'colaborador',
  specialty text,
  hours_per_day numeric(5,2) not null default 6,
  days_per_week integer not null default 6,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(coalesce(new.email,''),'@',1), 'Membro'),
    coalesce(new.raw_user_meta_data->>'role', 'colaborador')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  client text,
  status text not null default 'Planejamento',
  priority text not null default 'Média',
  progress numeric(5,4) not null default 0 check (progress >= 0 and progress <= 1),
  owner_id uuid references public.profiles(id) on delete set null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.commissions (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  client text,
  status text not null default 'Planejamento',
  priority text not null default 'Média',
  progress numeric(5,4) not null default 0 check (progress >= 0 and progress <= 1),
  owner_id uuid references public.profiles(id) on delete set null,
  deadline date,
  start_date date,
  map_name text,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.commission_members (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid not null references public.commissions(id) on delete cascade,
  profile_id uuid references public.profiles(id) on delete set null,
  collaborator_name text,
  role text,
  created_at timestamptz not null default now(),
  unique (commission_id, profile_id)
);

create table if not exists public.assets (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid not null references public.commissions(id) on delete cascade,
  name text not null,
  category text,
  map_name text,
  model_status boolean not null default false,
  model_by uuid references public.profiles(id) on delete set null,
  texture_status boolean not null default false,
  texture_by uuid references public.profiles(id) on delete set null,
  rig_status boolean not null default false,
  rig_by uuid references public.profiles(id) on delete set null,
  export_status boolean not null default false,
  export_by uuid references public.profiles(id) on delete set null,
  estimated_hours numeric(7,2) not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid references public.commissions(id) on delete cascade,
  asset_id uuid references public.assets(id) on delete cascade,
  title text not null,
  task_type text,
  assignee_id uuid references public.profiles(id) on delete set null,
  collaborator_name text,
  status text not null default 'Pendente',
  estimated_hours numeric(7,2) not null default 0,
  due_date date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.agenda_items (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid references public.commissions(id) on delete cascade,
  task_id uuid references public.tasks(id) on delete cascade,
  profile_id uuid references public.profiles(id) on delete set null,
  collaborator_name text,
  date date not null,
  task text not null,
  hours numeric(7,2) not null default 0,
  status text not null default 'Pendente',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id uuid,
  details jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

