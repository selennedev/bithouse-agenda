-- Updated-at helper
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array[
    'profiles','projects','commissions','commission_members','assets',
    'tasks','agenda_items','activity_log','settings'
  ]
  loop
    execute format('drop trigger if exists trg_updated_at_%I on public.%I', t, t);
    if t in ('profiles','projects','commissions','assets','tasks','agenda_items','settings') then
      execute format(
        'create trigger trg_updated_at_%I before update on public.%I for each row execute procedure public.set_updated_at()',
        t,t
      );
    end if;
  end loop;
end $$;

